/**
 * Twenty designs for the same room.
 * Every theme pairs a cinematic wallpaper "scene" with its own palette,
 * typography, caption treatment, panel treatment and ambient texture.
 * All of them are warm / quiet / late-night — nothing aggressive, nothing cyber.
 */

export type CaptionStyle = "bare" | "glass" | "plate" | "chip" | "stack" | "karaoke";
export type PanelStyle = "sheet" | "rail" | "list" | "memo" | "cards";
export type ChromeStyle = "bar" | "float" | "sidebarHead";
export type Particle = "rain" | "dust" | "ember" | "snow" | "none";

export interface Wallpaper {
  src: string;
  thumb: string;
}

export interface Theme {
  n: string;
  id: string;
  name: string;
  mood: string;
  scene: string;
  sceneNote: string;
  wall: Wallpaper;
  filter: string;
  overlays: string[];
  vignette: number;
  grain: number;
  particle: Particle;
  particleColor: string;
  time24: boolean;
  fonts: { ui: string; display: string; caption: string; fontLabel: string };
  caption: {
    style: CaptionStyle;
    align: "left" | "center";
    maxw: string;
    bottom: string;
    size: string;
    weight: number;
    tracking: string;
    leading: number;
    italic?: boolean;
    upper?: boolean;
  };
  panel: { style: PanelStyle; width: number };
  chrome: ChromeStyle;
  vars: Record<string, string>;
}

const px = (id: string, ext = "jpeg"): Wallpaper => {
  const base = `https://images.pexels.com/photos/${id}/pexels-photo-${id}.${ext}?auto=compress&cs=tinysrgb`;
  return {
    src: `${base}&fit=crop&h=900&w=1600`,
    thumb: `${base}&fit=crop&h=300&w=520`,
  };
};

