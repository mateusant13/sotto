"""Write docs/design-audit-20261021/INDEX.md from the measured shots.

Read-only over product/panel/*.json, demos/*/*/meta.json and the folders. This
is the provenance table: every link points at a file that exists on disk.
"""
import glob
import json
import os
import sys

sys.stdout.reconfigure(encoding='utf-8', errors='replace')

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))), 'docs', 'design-audit-20261021')
FAMILY = [
    ('Base directions (5)', ('theme-1', 'theme-2', 'theme-3', 'theme-4', 'theme-5')),
    ('Zip 2 panels (10)', ('GlassCards', 'Hairline', 'Paper', 'Quotes', 'Ledger',
                           'Feed', 'Bubbles', 'Timeline', 'Chips', 'Gutter')),
    ('Panel designs (5)', ('pd-bcast', 'pd-cine', 'pd-instr', 'pd-mano', 'pd-tele')),
]


def row(theme):
    p = os.path.join(ROOT, 'product', 'panel', theme + '.json')
    try:
        d = json.load(open(p, encoding='utf-8'))
    except Exception:
        return '| `%s` | - | - | - | - | - | - |' % theme
    b = d.get('brand') or {}
    live = (d.get('captions') or [{}])[-1]
    font = str(b.get('fontFamily') or '')
    font = font.split(',')[0].strip('"\' ')
    plate = b.get('rowBg') or '-'
    alpha = b.get('rowBgAlpha')
    plate_s = 'none' if not alpha else '%s @ %.2f' % (plate, alpha)
    rule = b.get('panelRuleW') or 0
    tw = (live.get('textBox') or {}).get('w') or 0
    # A cinematic skin hides the stock list: its rows measure 0 wide, and the
    # live line was measured from the skin by brand-bridge (the `face`/`live`
    # columns are the skin's own). Say so instead of printing a fake 0 px.
    tw_s = 'skin' if tw < 1 else '%s px' % tw
    over = '-' if tw < 1 else (
        'YES' if (d.get('overflowing') or d.get('overflowingBottom')) else 'no')
    return ('| [%s](product/panel/%s.png) | %s | %s | %s | %s | %s | %s |'
            % (theme, theme, font or '-', b.get('panelLivePx', '-'),
               tw_s, plate_s, rule, over))


def main():
    lines = []
    lines.append('# INDEX - every shot in this audit\n')
    lines.append('Generated by `_main/_design-lane/make-index.py` from the JSON '
                 'each shot writes. Links are relative to this folder.\n')
    lines.append('| surface | count | notes |')
    lines.append('|---|---:|---|')
    lines.append('| Product panels | 45 | 380 x 900, true layout via CDP |')
    lines.append('| Product strips | 45 | 1040 x 40, the bottom bar |')
    lines.append('| Product strip + float | 45 | 1040 x 220, bar plus floated caption |')
    lines.append('| Native overlay stills | 45 | the real `caption_overlay.py` GDI+ render |')
    lines.append('| Zip demos (app) | 50 | fresh, each zip at its own viewport |')
    lines.append('| Zip demos (panel) | 50 | the demo panel clipped out |')
    lines.append('')
    lines.append('Contact sheets: [product panels](contact-sheets/product-panel.png) · '
                 '[strips](contact-sheets/product-strip.png) · '
                 '[strip + float](contact-sheets/product-strip-float.png) · '
                 '[native](contact-sheets/native-overlay.png) · '
                 '[skin comparison](contact-sheets/comparison-last-train.png) · '
                 '[six skins, idle/filled](contact-sheets/skins-idle-filled.png)\n')

    themes = sorted(os.path.splitext(os.path.basename(p))[0]
                    for p in glob.glob(os.path.join(ROOT, 'product', 'panel', '*.png')))
    known = set()
    lines.append('## Product themes\n')
    for title, names in FAMILY:
        present = [n for n in names if n in themes]
        known.update(present)
        lines.append('### %s\n' % title)
        lines.append('| theme | face | live | text column | plate | rule | overflow |')
        lines.append('|---|---|---:|---:|---|---:|---|')
        for t in present:
            lines.append(row(t))
        lines.append('')
    cine = [t for t in themes if t.startswith('cine-')]
    if cine:
        lines.append('### Cinematic skins (25)\n')
        lines.append('| theme | face | live | text column | plate | rule | overflow |')
        lines.append('|---|---|---:|---:|---|---:|---|')
        for t in cine:
            lines.append(row(t))
        lines.append('')
        known.update(cine)
    rest = [t for t in themes if t not in known]
    if rest:
        lines.append('### Other\n')
        lines.append('| theme | face | live | text column | plate | rule | overflow |')
        lines.append('|---|---|---:|---:|---|---:|---|')
        for t in rest:
            lines.append(row(t))
        lines.append('')

    lines.append('## Zip demos\n')
    lines.append('| zip | demos | app sheet | panel sheet |')
    lines.append('|---|---:|---|---|')
    for group in sorted(glob.glob(os.path.join(ROOT, 'demos', '*'))):
        if not os.path.isdir(group):
            continue
        name = os.path.basename(group)
        n = len(glob.glob(os.path.join(group, '*', 'app.png')))
        lines.append('| %s | %d | [app](contact-sheets/demos-%s-app.png) | '
                     '[panel](contact-sheets/demos-%s-panel.png) |'
                     % (name, n, name, name))
    lines.append('')
    lines.append('## Full-size files\n')
    lines.append('- Product: `product/<panel|strip|strip-float>/<theme>.png` and `.json`')
    lines.append('- Native overlay: `native/<theme>.png`')
    lines.append('- Demos: `demos/<zip>/<nn-name>/app.png`, `panel.png`, `meta.json`')
    lines.append('- Contact sheets: `contact-sheets/`')
    lines.append('- Skin states (six shipped skins): `states/idle/<theme>.png`, `states/filled/<theme>.png`')
    lines.append('')
    out = os.path.join(ROOT, 'INDEX.md')
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', out, len(lines), 'lines')


if __name__ == '__main__':
    main()
